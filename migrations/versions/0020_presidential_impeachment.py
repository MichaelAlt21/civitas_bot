branch_labels = None
depends_on = None


def _set_office_overlap_guard(*, impeachment: bool) -> None:
    join = """
        LEFT JOIN impeachment_confirmations AS ended
            ON ended.guild_id = term.guild_id AND ended.term_id = term.id
    """ if impeachment else ""
    ends_at = "coalesce(ended.confirmed_at, term.ends_at)" if impeachment else "term.ends_at"
    op.execute(f"""
        CREATE OR REPLACE FUNCTION civitas_prevent_overlapping_office() RETURNS trigger
        LANGUAGE plpgsql AS $$
        BEGIN
            PERFORM id FROM guilds WHERE id = NEW.guild_id FOR NO KEY UPDATE;
            IF EXISTS (
                SELECT 1 FROM public_offices AS term {join}
                    WHERE term.guild_id = NEW.guild_id AND term.office = NEW.office
                        AND term.election_id <> NEW.election_id
                        AND term.starts_at < NEW.ends_at AND NEW.starts_at < {ends_at}
            ) THEN
                RAISE EXCEPTION 'Office mandates cannot overlap' USING ERRCODE = 'check_violation';
            END IF;
            RETURN NEW;
        END;
        $$
    """)


def _create_tables() -> None:
    op.create_unique_constraint("uq_public_offices_guild_id", "public_offices", ["guild_id", "id"])
    op.execute("""
        CREATE TABLE impeachment_ballots (
            id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            guild_id bigint NOT NULL,
            term_id bigint NOT NULL,
            eligible_citizen_ids bigint[] NOT NULL,
            quorum integer NOT NULL,
            opened_by_citizen_id bigint NOT NULL,
            opened_at timestamptz NOT NULL,
            request_key varchar(128) NOT NULL,
            CONSTRAINT uq_impeachment_ballots_guild_id UNIQUE (guild_id, id),
            CONSTRAINT uq_impeachment_ballots_term_link UNIQUE (guild_id, id, term_id),
            CONSTRAINT uq_impeachment_ballots_request UNIQUE (guild_id, request_key),
            CONSTRAINT fk_impeachment_ballots_term FOREIGN KEY (guild_id, term_id)
                REFERENCES public_offices(guild_id, id),
            CONSTRAINT fk_impeachment_ballots_opener FOREIGN KEY (guild_id, opened_by_citizen_id)
                REFERENCES citizens(guild_id, id),
            CONSTRAINT ck_impeachment_ballots_rules CHECK (
                quorum > 0 AND quorum <= cardinality(eligible_citizen_ids) AND length(btrim(request_key)) > 0
            )
        )
    """)
    op.execute("""
        CREATE TABLE impeachment_protocols (
            guild_id bigint NOT NULL,
            impeachment_id bigint NOT NULL,
            source_url text NOT NULL,
            participants integer NOT NULL,
            votes_for integer NOT NULL,
            recorded_by_citizen_id bigint NOT NULL,
            recorded_at timestamptz NOT NULL,
            public_reason text NOT NULL,
            PRIMARY KEY (guild_id, impeachment_id),
            CONSTRAINT fk_impeachment_protocols_ballot FOREIGN KEY (guild_id, impeachment_id)
                REFERENCES impeachment_ballots(guild_id, id),
            CONSTRAINT fk_impeachment_protocols_recorder FOREIGN KEY (guild_id, recorded_by_citizen_id)
                REFERENCES citizens(guild_id, id),
            CONSTRAINT ck_impeachment_protocols_votes CHECK (participants >= 0 AND votes_for BETWEEN 0 AND participants),
            CONSTRAINT ck_impeachment_protocols_reason CHECK (length(btrim(public_reason)) BETWEEN 1 AND 200)
        )
    """)
    op.execute("""
        CREATE UNIQUE INDEX uq_impeachment_protocols_source
        ON impeachment_protocols (guild_id, civitas_election_source_key(source_url))
    """)
    op.execute("""
        CREATE TABLE impeachment_confirmations (
            term_id bigint PRIMARY KEY,
            guild_id bigint NOT NULL,
            impeachment_id bigint NOT NULL,
            confirmed_by_citizen_id bigint NOT NULL,
            confirmed_at timestamptz NOT NULL,
            confirmation_reason text NOT NULL,
            CONSTRAINT fk_impeachment_confirmations_term_link FOREIGN KEY (guild_id, impeachment_id, term_id)
                REFERENCES impeachment_ballots(guild_id, id, term_id),
            CONSTRAINT fk_impeachment_confirmations_protocol FOREIGN KEY (guild_id, impeachment_id)
                REFERENCES impeachment_protocols(guild_id, impeachment_id),
            CONSTRAINT fk_impeachment_confirmations_actor FOREIGN KEY (guild_id, confirmed_by_citizen_id)
                REFERENCES citizens(guild_id, id),
            CONSTRAINT ck_impeachment_confirmations_reason CHECK (length(btrim(confirmation_reason)) BETWEEN 1 AND 200)
        )
    """)


def _install_guards() -> None:
    for table in ("impeachment_ballots", "impeachment_protocols", "impeachment_confirmations"):
        op.execute(f"""
            CREATE TRIGGER impeachment_history_immutable
            BEFORE UPDATE OR DELETE OR TRUNCATE ON {table}
            FOR EACH STATEMENT EXECUTE FUNCTION civitas_reject_ledger_edit()
        """)
    op.execute("""
        CREATE FUNCTION civitas_guard_impeachment_ballot() RETURNS trigger
        LANGUAGE plpgsql AS $$
        DECLARE
            mandate public_offices%ROWTYPE;
        BEGIN
            PERFORM id FROM guilds WHERE id = NEW.guild_id FOR NO KEY UPDATE;
            SELECT * INTO mandate FROM public_offices WHERE guild_id = NEW.guild_id AND id = NEW.term_id;
            IF mandate.id IS NULL OR mandate.office <> 'PRESIDENT'
                OR NEW.opened_at < mandate.starts_at OR NEW.opened_at >= mandate.ends_at
                OR EXISTS (SELECT 1 FROM impeachment_confirmations WHERE term_id = mandate.id)
                OR NEW.opened_by_citizen_id = mandate.holder_citizen_id
                OR NOT EXISTS (
                    SELECT 1 FROM citizens WHERE guild_id = NEW.guild_id
                        AND id = NEW.opened_by_citizen_id AND status = 'VERIFIED'
                )
            THEN
                RAISE EXCEPTION 'Impeachment requires an active president and independent opener'
                    USING ERRCODE = 'check_violation';
            END IF;
            IF cardinality(NEW.eligible_citizen_ids) <> (
                SELECT count(*) FROM citizens WHERE guild_id = NEW.guild_id
                    AND status = 'VERIFIED' AND id = ANY(NEW.eligible_citizen_ids)
            ) THEN
                RAISE EXCEPTION 'Impeachment voters must be distinct verified citizens of the same guild'
                    USING ERRCODE = 'check_violation';
            END IF;
            RETURN NEW;
        END;
        $$
    """)
    op.execute("""
        CREATE FUNCTION civitas_guard_impeachment_protocol() RETURNS trigger
        LANGUAGE plpgsql AS $$
        DECLARE
            ballot impeachment_ballots%ROWTYPE;
            mandate public_offices%ROWTYPE;
            source_key text;
        BEGIN
            PERFORM id FROM guilds WHERE id = NEW.guild_id FOR NO KEY UPDATE;
            SELECT * INTO ballot FROM impeachment_ballots WHERE guild_id = NEW.guild_id AND id = NEW.impeachment_id;
            SELECT * INTO mandate FROM public_offices WHERE guild_id = NEW.guild_id AND id = ballot.term_id;
            IF mandate.id IS NULL OR NEW.recorded_at < ballot.opened_at OR NEW.recorded_at >= mandate.ends_at
                OR EXISTS (SELECT 1 FROM impeachment_confirmations WHERE term_id = mandate.id)
                OR NEW.recorded_by_citizen_id = mandate.holder_citizen_id
                OR NOT EXISTS (
                    SELECT 1 FROM citizens WHERE guild_id = NEW.guild_id
                        AND id = NEW.recorded_by_citizen_id AND status = 'VERIFIED'
                )
                OR NEW.participants > cardinality(ballot.eligible_citizen_ids)
            THEN
                RAISE EXCEPTION 'Impeachment protocol does not match an active independent ballot'
                    USING ERRCODE = 'check_violation';
            END IF;
            source_key := civitas_election_source_key(NEW.source_url);
            IF source_key IS NULL OR EXISTS (
                SELECT 1 FROM election_poll_sources WHERE guild_id = NEW.guild_id AND source_url = source_key
            ) THEN
                RAISE EXCEPTION 'Poll source is invalid or belongs to another vote' USING ERRCODE = 'check_violation';
            END IF;
            RETURN NEW;
        END;
        $$
    """)
    op.execute("""
        CREATE FUNCTION civitas_guard_impeachment_confirmation() RETURNS trigger
        LANGUAGE plpgsql AS $$
        DECLARE
            ballot impeachment_ballots%ROWTYPE;
            mandate public_offices%ROWTYPE;
            protocol impeachment_protocols%ROWTYPE;
        BEGIN
            SELECT * INTO mandate FROM public_offices WHERE guild_id = NEW.guild_id AND id = NEW.term_id;
            -- Elected treasury mutations lock the acting citizen before checking power.
            PERFORM id FROM citizens WHERE guild_id = NEW.guild_id
                AND id IN (mandate.holder_citizen_id, NEW.confirmed_by_citizen_id)
                ORDER BY id FOR NO KEY UPDATE;
            PERFORM id FROM guilds WHERE id = NEW.guild_id FOR NO KEY UPDATE;
            SELECT * INTO ballot FROM impeachment_ballots WHERE guild_id = NEW.guild_id AND id = NEW.impeachment_id;
            SELECT * INTO protocol FROM impeachment_protocols
                WHERE guild_id = NEW.guild_id AND impeachment_id = ballot.id;
            IF protocol.impeachment_id IS NULL OR mandate.id IS NULL OR ballot.term_id <> mandate.id
                OR NEW.confirmed_at < protocol.recorded_at OR NEW.confirmed_at >= mandate.ends_at
                OR NEW.confirmed_by_citizen_id IN (mandate.holder_citizen_id, protocol.recorded_by_citizen_id)
                OR NOT EXISTS (
                    SELECT 1 FROM citizens WHERE guild_id = NEW.guild_id
                        AND id = NEW.confirmed_by_citizen_id AND status = 'VERIFIED'
                )
                OR protocol.participants < ballot.quorum
                OR protocol.votes_for::bigint * 3 < protocol.participants::bigint * 2
            THEN
                RAISE EXCEPTION 'Impeachment requires a qualifying vote and an independent second attestation'
                    USING ERRCODE = 'check_violation';
            END IF;
            RETURN NEW;
        END;
        $$
    """)
    for action, table in (
        ("ballot", "impeachment_ballots"),
        ("protocol", "impeachment_protocols"),
        ("confirmation", "impeachment_confirmations"),
    ):
        op.execute(f"""
            CREATE TRIGGER impeachment_guard_{action}
            BEFORE INSERT ON {table}
            FOR EACH ROW EXECUTE FUNCTION civitas_guard_impeachment_{action}()
        """)
    op.execute("""
        CREATE FUNCTION civitas_guard_election_source_exclusive() RETURNS trigger
        LANGUAGE plpgsql AS $$
        BEGIN
            PERFORM id FROM guilds WHERE id = NEW.guild_id FOR NO KEY UPDATE;
            IF EXISTS (
                SELECT 1 FROM impeachment_protocols WHERE guild_id = NEW.guild_id
                    AND civitas_election_source_key(source_url) = NEW.source_url
            ) THEN
                RAISE EXCEPTION 'Poll source belongs to an impeachment vote' USING ERRCODE = 'check_violation';
            END IF;
            RETURN NEW;
        END;
        $$
    """)
    op.execute("""
        CREATE TRIGGER election_poll_sources_impeachment_exclusive
        BEFORE INSERT ON election_poll_sources
        FOR EACH ROW EXECUTE FUNCTION civitas_guard_election_source_exclusive()
    """)


def upgrade() -> None:
    _create_tables()
    _install_guards()
    _set_office_overlap_guard(impeachment=True)


def downgrade() -> None:
    op.execute("""
        DO $$ BEGIN
            IF EXISTS (SELECT 1 FROM impeachment_ballots) THEN
                RAISE EXCEPTION 'Cannot downgrade government while impeachment history exists';
            END IF;
        END $$
    """)
    _set_office_overlap_guard(impeachment=False)
    op.execute("DROP TRIGGER election_poll_sources_impeachment_exclusive ON election_poll_sources")
    op.execute("DROP FUNCTION civitas_guard_election_source_exclusive()")
    for action, table in (
        ("confirmation", "impeachment_confirmations"),
        ("protocol", "impeachment_protocols"),
        ("ballot", "impeachment_ballots"),
    ):
        op.drop_table(table)
        op.execute(f"DROP FUNCTION civitas_guard_impeachment_{action}()")
    op.drop_constraint("uq_public_offices_guild_id", "public_offices", type_="unique")
