    _set_account_constraints(private_jobs=False)
    op.drop_constraint("fk_financial_accounts_private_job", "financial_accounts", type_="foreignkey")
    op.drop_column("financial_accounts", "private_job_id")
    op.drop_table("private_jobs")
    op.execute("DROP FUNCTION civitas_validate_private_job_escrow()")
    op.execute("DROP FUNCTION civitas_guard_private_job_transition()")
