def _install_lifecycle_guard() -> None:
    op.execute("""
        CREATE FUNCTION civitas_guard_private_job_transition() RETURNS trigger
        LANGUAGE plpgsql AS $$
        BEGIN
            IF TG_OP = 'DELETE' THEN
                RAISE EXCEPTION 'Private job history is immutable' USING ERRCODE = 'check_violation';
            END IF;
            IF TG_OP = 'INSERT' THEN
                IF NEW.status <> 'OPEN' OR NOT EXISTS (
                    SELECT 1 FROM organizations
                    WHERE guild_id = NEW.guild_id AND id = NEW.company_id AND owner_citizen_id = NEW.owner_citizen_id
                ) THEN
                    RAISE EXCEPTION 'New private job must be opened by the company owner' USING ERRCODE = 'check_violation';
                END IF;
                RETURN NEW;
            END IF;
            IF NOT (
                (OLD.status = 'OPEN' AND NEW.status IN ('CLAIMED', 'CANCELLED')) OR
                (OLD.status = 'CLAIMED' AND NEW.status IN ('SUBMITTED', 'CANCELLED')) OR
                (OLD.status = 'SUBMITTED' AND NEW.status IN ('PAID', 'DISPUTED')) OR
                (OLD.status = 'DISPUTED' AND NEW.status IN ('PAID', 'CANCELLED'))
            ) OR ROW(NEW.id, NEW.guild_id, NEW.company_id, NEW.owner_citizen_id, NEW.title, NEW.terms,
                NEW.amount, NEW.deadline, NEW.request_key, NEW.publication_reason, NEW.created_at)
            IS DISTINCT FROM ROW(OLD.id, OLD.guild_id, OLD.company_id, OLD.owner_citizen_id, OLD.title, OLD.terms,
                OLD.amount, OLD.deadline, OLD.request_key, OLD.publication_reason, OLD.created_at)
            OR (NEW.status <> 'CLAIMED' AND ROW(NEW.worker_citizen_id, NEW.claimed_at)
                IS DISTINCT FROM ROW(OLD.worker_citizen_id, OLD.claimed_at))
            OR (NEW.status <> 'SUBMITTED' AND ROW(NEW.submitted_at, NEW.evidence)
                IS DISTINCT FROM ROW(OLD.submitted_at, OLD.evidence))
            OR (NEW.status <> 'DISPUTED' AND ROW(NEW.disputed_at, NEW.disputed_by_citizen_id, NEW.dispute_reason)
                IS DISTINCT FROM ROW(OLD.disputed_at, OLD.disputed_by_citizen_id, OLD.dispute_reason))
            THEN
                RAISE EXCEPTION 'Invalid private job transition' USING ERRCODE = 'check_violation';
            END IF;

            IF (NEW.status = 'DISPUTED' AND NEW.disputed_at < NEW.deadline
                    AND NEW.disputed_by_citizen_id NOT IN (NEW.owner_citizen_id, NEW.worker_citizen_id))
                OR (OLD.status = 'DISPUTED' AND NEW.closed_by_citizen_id IN (NEW.owner_citizen_id, NEW.worker_citizen_id))
                OR (OLD.status = 'SUBMITTED' AND NEW.status = 'PAID' AND NEW.closed_by_citizen_id <> NEW.owner_citizen_id)
                OR (NEW.status = 'CANCELLED' AND OLD.status IN ('OPEN', 'CLAIMED')
                    AND NEW.closed_at < NEW.deadline
                    AND NEW.closed_by_citizen_id IS DISTINCT FROM NEW.owner_citizen_id
                    AND NEW.closed_by_citizen_id IS DISTINCT FROM NEW.worker_citizen_id)
            THEN
                RAISE EXCEPTION 'Private job decision has an invalid actor' USING ERRCODE = 'check_violation';
            END IF;
            RETURN NEW;
        END;
        $$
    """)
    op.execute("""
        CREATE TRIGGER guard_private_job_transition BEFORE INSERT OR UPDATE OR DELETE ON private_jobs
        FOR EACH ROW EXECUTE FUNCTION civitas_guard_private_job_transition()
    """)


def _install_escrow_guards() -> None:
    op.execute("""
        CREATE FUNCTION civitas_validate_private_job_escrow() RETURNS trigger
        LANGUAGE plpgsql AS $$
        DECLARE
            job private_jobs%ROWTYPE;
            fund financial_transactions%ROWTYPE;
            terminal financial_transactions%ROWTYPE;
            target_id bigint;
            escrow_id bigint;
            company_account_id bigint;
            worker_account_id bigint;
            destination_id bigint;
            expected_kind text;
        BEGIN
            IF TG_TABLE_NAME = 'financial_transactions' THEN
                SELECT account.private_job_id INTO target_id FROM ledger_entries AS entry
                JOIN financial_accounts AS account ON account.id = entry.account_id
                WHERE entry.transaction_id = NEW.id AND account.private_job_id IS NOT NULL;
            ELSE
                target_id := NEW.id;
            END IF;
            SELECT * INTO job FROM private_jobs WHERE guild_id = NEW.guild_id AND id = target_id;
            IF job.id IS NULL THEN
                RAISE EXCEPTION 'Private job posting requires its job and escrow' USING ERRCODE = 'check_violation';
            END IF;

            SELECT id INTO escrow_id FROM financial_accounts
                WHERE guild_id = job.guild_id AND kind = 'ESCROW' AND private_job_id = job.id;
            SELECT id INTO company_account_id FROM financial_accounts
                WHERE guild_id = job.guild_id AND kind = 'COMPANY' AND organization_id = job.company_id;
            SELECT * INTO fund FROM financial_transactions
                WHERE guild_id = job.guild_id AND kind = 'PRIVATE_JOB_FUND'
                AND idempotency_key = 'private_job_fund:' || job.id;
            IF fund.id IS NULL OR fund.actor_citizen_id IS DISTINCT FROM job.owner_citizen_id
                OR fund.reason IS DISTINCT FROM job.publication_reason OR fund.entry_count <> 2
                OR NOT EXISTS (SELECT 1 FROM ledger_entries
                    WHERE transaction_id = fund.id AND account_id = company_account_id AND delta = -job.amount)
                OR NOT EXISTS (SELECT 1 FROM ledger_entries
                    WHERE transaction_id = fund.id AND account_id = escrow_id AND delta = job.amount)
            THEN
                RAISE EXCEPTION 'Private job funding must reserve the agreed company funds' USING ERRCODE = 'check_violation';
            END IF;

            IF job.status IN ('PAID', 'CANCELLED') THEN
                SELECT * INTO terminal FROM financial_transactions WHERE id = job.payout_transaction_id;
                IF job.status = 'PAID' THEN
                    SELECT id INTO worker_account_id FROM financial_accounts
                        WHERE guild_id = job.guild_id AND kind = 'PERSONAL' AND citizen_id = job.worker_citizen_id;
                    destination_id := worker_account_id;
                    expected_kind := 'PRIVATE_JOB_PAY';
                ELSE
                    destination_id := company_account_id;
                    expected_kind := 'PRIVATE_JOB_REFUND';
                END IF;
                IF terminal.id IS NULL OR terminal.kind <> expected_kind
                    OR terminal.idempotency_key <> lower(expected_kind) || ':' || job.id
                    OR terminal.actor_citizen_id IS DISTINCT FROM job.closed_by_citizen_id
                    OR terminal.reason IS DISTINCT FROM job.close_reason OR terminal.entry_count <> 2
                    OR NOT EXISTS (SELECT 1 FROM ledger_entries
                        WHERE transaction_id = terminal.id AND account_id = escrow_id AND delta = -job.amount)
                    OR NOT EXISTS (SELECT 1 FROM ledger_entries
                        WHERE transaction_id = terminal.id AND account_id = destination_id AND delta = job.amount)
                THEN
                    RAISE EXCEPTION 'Private job closure must transfer its full escrow balance' USING ERRCODE = 'check_violation';
                END IF;
            END IF;

            IF TG_TABLE_NAME = 'financial_transactions'
                AND NEW.id IS DISTINCT FROM fund.id AND NEW.id IS DISTINCT FROM terminal.id
            THEN
                RAISE EXCEPTION 'Private job posting is not linked to its job' USING ERRCODE = 'check_violation';
            END IF;
            RETURN NULL;
        END;
        $$
    """)
    op.execute("""
        CREATE CONSTRAINT TRIGGER private_job_validate_escrow
        AFTER INSERT OR UPDATE ON private_jobs DEFERRABLE INITIALLY DEFERRED
        FOR EACH ROW EXECUTE FUNCTION civitas_validate_private_job_escrow()
    """)
    op.execute(f"""
        CREATE CONSTRAINT TRIGGER private_job_validate_posting
        AFTER INSERT ON financial_transactions DEFERRABLE INITIALLY DEFERRED
        FOR EACH ROW WHEN (NEW.kind IN ({_PRIVATE_POSTINGS}))
        EXECUTE FUNCTION civitas_validate_private_job_escrow()
    """)


def downgrade() -> None:
    op.execute("""
        DO $$ BEGIN
            IF EXISTS (SELECT 1 FROM private_jobs) THEN
                RAISE EXCEPTION 'Cannot downgrade while private job history exists';
            END IF;
        END $$
    """)
    op.execute("DROP TRIGGER private_job_validate_posting ON financial_transactions")
