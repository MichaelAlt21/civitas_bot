def _install_budget_guards() -> None:
    op.execute("""
        CREATE FUNCTION civitas_validate_contract_budget() RETURNS trigger
        LANGUAGE plpgsql AS $$
        DECLARE
            target_period_id bigint;
            budget budget_periods%ROWTYPE;
            article budget_articles%ROWTYPE;
            approval contract_budget_approvals%ROWTYPE;
            spent_sum numeric;
            reserved_sum numeric;
        BEGIN
            IF TG_TABLE_NAME = 'budget_periods' THEN
                target_period_id := NEW.id;
            ELSIF TG_TABLE_NAME = 'state_contracts' THEN
                target_period_id := NEW.budget_period_id;
            ELSIF TG_OP = 'DELETE' THEN
                target_period_id := OLD.period_id;
            ELSE
                target_period_id := NEW.period_id;
            END IF;
            IF target_period_id IS NULL THEN
                RETURN NULL;
            END IF;
            SELECT * INTO STRICT budget FROM budget_periods WHERE id = target_period_id;
            SELECT * INTO article FROM budget_articles
                WHERE period_id = target_period_id AND code = 'state_contracts';
            SELECT * INTO approval FROM contract_budget_approvals WHERE period_id = target_period_id;
            IF (article.id IS NULL) <> (approval.period_id IS NULL)
                OR article.cap > budget.overall_cap
                OR approval.activated_at < budget.start_at OR approval.activated_at >= budget.end_at
            THEN
                RAISE EXCEPTION 'The state contract article must match its approval and period'
                    USING ERRCODE = 'check_violation';
            END IF;
            SELECT
                coalesce(sum(amount) FILTER (WHERE status = 'PAID'), 0),
                coalesce(sum(amount) FILTER (WHERE status IN ('RESERVED', 'SUBMITTED')), 0)
                INTO spent_sum, reserved_sum
                FROM state_contracts WHERE budget_period_id = target_period_id;
            IF coalesce(article.spent, 0) <> spent_sum OR coalesce(article.reserved, 0) <> reserved_sum
                OR budget.reserved_total <> reserved_sum
            THEN
                RAISE EXCEPTION 'State contract budget counters must match contract receipts'
                    USING ERRCODE = 'check_violation';
            END IF;
            SELECT coalesce(sum(spent), 0), coalesce(sum(reserved), 0)
                INTO spent_sum, reserved_sum FROM budget_articles WHERE period_id = target_period_id;
            IF budget.spent_total <> spent_sum OR budget.reserved_total <> reserved_sum THEN
                RAISE EXCEPTION 'Weekly budget counters must match its articles'
                    USING ERRCODE = 'check_violation';
            END IF;
            RETURN NULL;
        END;
        $$
    """)
    for table, events in (
        ("budget_periods", "INSERT OR UPDATE"),
        ("budget_articles", "INSERT OR UPDATE OR DELETE"),
        ("contract_budget_approvals", "INSERT"),
        ("state_contracts", "UPDATE"),
    ):
        op.execute(f"""
            CREATE CONSTRAINT TRIGGER treasury_validate_budget
            AFTER {events} ON {table} DEFERRABLE INITIALLY DEFERRED
            FOR EACH ROW EXECUTE FUNCTION civitas_validate_contract_budget()
        """)


def _install_cash_guards() -> None:
    op.execute("""
        CREATE FUNCTION civitas_validate_reserved_cash() RETURNS trigger
        LANGUAGE plpgsql AS $$
        DECLARE
            treasury_id bigint;
            balance numeric;
            reserved numeric;
        BEGIN
            IF TG_TABLE_NAME = 'ledger_entries' THEN
                IF NOT EXISTS (
                    SELECT 1 FROM financial_accounts WHERE id = NEW.account_id AND kind = 'TREASURY'
                ) THEN
                    RETURN NULL;
                END IF;
            END IF;
            SELECT id INTO treasury_id FROM financial_accounts
                WHERE guild_id = NEW.guild_id AND kind = 'TREASURY' FOR NO KEY UPDATE;
            SELECT coalesce(sum(reserved_total), 0) INTO reserved FROM budget_periods
                WHERE guild_id = NEW.guild_id;
            SELECT coalesce(sum(delta), 0) INTO balance FROM ledger_entries WHERE account_id = treasury_id;
            IF balance < reserved THEN
                RAISE EXCEPTION 'Treasury balance cannot fall below guaranteed cash reserves'
                    USING ERRCODE = 'check_violation';
            END IF;
            RETURN NULL;
        END;
        $$
    """)
    op.execute("""
        CREATE CONSTRAINT TRIGGER treasury_cash_posting
        AFTER INSERT ON ledger_entries DEFERRABLE INITIALLY DEFERRED
        FOR EACH ROW WHEN (NEW.delta < 0) EXECUTE FUNCTION civitas_validate_reserved_cash()
    """)
    op.execute("""
        CREATE CONSTRAINT TRIGGER treasury_cash_reservation
        AFTER UPDATE ON budget_periods DEFERRABLE INITIALLY DEFERRED
        FOR EACH ROW WHEN (NEW.reserved_total <> OLD.reserved_total)
        EXECUTE FUNCTION civitas_validate_reserved_cash()
    """)
    op.execute("""
        CREATE CONSTRAINT TRIGGER treasury_cash_initial_period
        AFTER INSERT ON budget_periods DEFERRABLE INITIALLY DEFERRED
        FOR EACH ROW WHEN (NEW.reserved_total > 0)
        EXECUTE FUNCTION civitas_validate_reserved_cash()
    """)


