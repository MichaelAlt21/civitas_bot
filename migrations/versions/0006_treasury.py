def _budget_constraints(*, reservations: bool) -> None:
    period = "overall_cap >= 0 AND spent_total BETWEEN 0 AND overall_cap"
    article = "personal_cap >= 0 AND spent BETWEEN 0 AND cap"
    if reservations:
        period += " AND reserved_total BETWEEN 0 AND overall_cap - spent_total"
        article += " AND reserved BETWEEN 0 AND cap - spent"
    op.drop_constraint("ck_budget_periods_cap", "budget_periods", type_="check")
    op.create_check_constraint("ck_budget_periods_cap", "budget_periods", period)
    op.drop_constraint("ck_budget_articles_cap", "budget_articles", type_="check")
    op.create_check_constraint("ck_budget_articles_cap", "budget_articles", article)


