def _install_posting_guard() -> None:
    op.execute("""
        CREATE FUNCTION civitas_validate_market_posting() RETURNS trigger
        LANGUAGE plpgsql AS $$
        DECLARE
            company organizations%ROWTYPE;
            purchase orders%ROWTYPE;
            escrow_id bigint;
            tax bigint;
            seller_net bigint;
        BEGIN
            IF NEW.kind NOT IN ('COMPANY_FEE', 'ORDER_FUND', 'ORDER_SETTLE', 'ORDER_REFUND') THEN
                IF EXISTS (
                    SELECT 1 FROM ledger_entries AS entry JOIN financial_accounts AS a ON a.id = entry.account_id
                    WHERE entry.transaction_id = NEW.id AND a.kind IN ('COMPANY', 'ESCROW')
                ) THEN
                    RAISE EXCEPTION 'Company and escrow accounts require a market operation'
                        USING ERRCODE = 'check_violation';
                END IF;
                RETURN NULL;
            END IF;
            IF NEW.kind = 'COMPANY_FEE' THEN
                SELECT * INTO company FROM organizations WHERE guild_id = NEW.guild_id
                    AND NEW.idempotency_key = 'company_fee:' || id;
                IF company.id IS NULL OR company.fee_paid <= 0 OR NEW.entry_count <> 2
                    OR NEW.actor_citizen_id IS DISTINCT FROM company.owner_citizen_id
                    OR NOT EXISTS (
                        SELECT 1 FROM ledger_entries AS entry JOIN financial_accounts AS a ON a.id = entry.account_id
                        WHERE entry.transaction_id = NEW.id AND a.kind = 'PERSONAL'
                            AND a.citizen_id = company.owner_citizen_id AND entry.delta = -company.fee_paid
                    ) OR NOT EXISTS (
                        SELECT 1 FROM ledger_entries AS entry JOIN financial_accounts AS a ON a.id = entry.account_id
                        WHERE entry.transaction_id = NEW.id AND a.kind = 'TREASURY' AND entry.delta = company.fee_paid
                    ) THEN
                    RAISE EXCEPTION 'Company fee must move from the founder to the treasury'
                        USING ERRCODE = 'check_violation';
                END IF;
                RETURN NULL;
            END IF;

            SELECT * INTO purchase FROM orders WHERE guild_id = NEW.guild_id
                AND NEW.idempotency_key = lower(NEW.kind) || ':' || id;
            SELECT id INTO escrow_id FROM financial_accounts
                WHERE guild_id = NEW.guild_id AND kind = 'ESCROW' AND order_id = purchase.id;
            IF escrow_id IS NULL THEN
                RAISE EXCEPTION 'Market posting must identify its order escrow' USING ERRCODE = 'check_violation';
            END IF;
            IF NEW.kind = 'ORDER_FUND' THEN
                IF NEW.entry_count <> 2 OR NEW.actor_citizen_id IS DISTINCT FROM purchase.buyer_citizen_id
                    OR NOT EXISTS (
                        SELECT 1 FROM ledger_entries WHERE transaction_id = NEW.id
                            AND account_id = escrow_id AND delta = purchase.price
                    ) OR NOT EXISTS (
                        SELECT 1 FROM ledger_entries WHERE transaction_id = NEW.id
                            AND account_id = purchase.buyer_account_id AND delta = -purchase.price
                    ) THEN
                    RAISE EXCEPTION 'Order funding must move the purchase price into escrow'
                        USING ERRCODE = 'check_violation';
                END IF;
                RETURN NULL;
            END IF;
            IF NEW.actor_citizen_id IS DISTINCT FROM purchase.closed_by_citizen_id
                OR NEW.reason IS DISTINCT FROM purchase.close_reason OR NOT EXISTS (
                SELECT 1 FROM ledger_entries WHERE transaction_id = NEW.id
                    AND account_id = escrow_id AND delta = -purchase.price
            ) THEN
                RAISE EXCEPTION 'Order closure must release the full escrow balance' USING ERRCODE = 'check_violation';
            END IF;
            IF NEW.kind = 'ORDER_REFUND' THEN
                IF purchase.status <> 'REFUNDED' OR NEW.entry_count <> 2 OR NOT EXISTS (
                    SELECT 1 FROM ledger_entries WHERE transaction_id = NEW.id
                        AND account_id = purchase.buyer_account_id AND delta = purchase.price
                ) THEN
                    RAISE EXCEPTION 'Order refund must return the full amount to the original account'
                        USING ERRCODE = 'check_violation';
                END IF;
                RETURN NULL;
            END IF;

            tax := div(purchase.price::numeric * purchase.tax_bp, 10000);
            seller_net := purchase.price - tax;
            IF purchase.status <> 'COMPLETED'
                OR NEW.entry_count <> 1 + (tax > 0)::integer + (seller_net > 0)::integer
                OR (tax > 0 AND NOT EXISTS (
                    SELECT 1 FROM ledger_entries AS entry JOIN financial_accounts AS a ON a.id = entry.account_id
                    WHERE entry.transaction_id = NEW.id AND a.kind = 'TREASURY' AND entry.delta = tax
                )) OR (seller_net > 0 AND NOT EXISTS (
                    SELECT 1 FROM ledger_entries AS entry JOIN financial_accounts AS a ON a.id = entry.account_id
                    WHERE entry.transaction_id = NEW.id AND a.kind = 'COMPANY'
                        AND a.organization_id = purchase.seller_company_id AND entry.delta = seller_net
                ))
            THEN
                RAISE EXCEPTION 'Order settlement must use the seller and tax snapshot' USING ERRCODE = 'check_violation';
            END IF;
            RETURN NULL;
        END;
        $$
    """)
    op.execute("""
        CREATE CONSTRAINT TRIGGER market_validate_posting
        AFTER INSERT ON financial_transactions DEFERRABLE INITIALLY DEFERRED
        FOR EACH ROW EXECUTE FUNCTION civitas_validate_market_posting()
    """)


